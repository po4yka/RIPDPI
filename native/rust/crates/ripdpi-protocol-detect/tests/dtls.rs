use ripdpi_protocol_detect::classify_l7;
use ripdpi_strategy_trait::L7Protocol;

#[test]
fn detects_dtls_client_hello_sample_payload() {
    let client_hello = [
        0x16, 0xFE, 0xFD, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x2F, 0x01, 0x00, 0x00, 0x23, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x23, 0xFE, 0xFD, 0x66, 0x31, 0x9A, 0x70, 0x00, 0x00, 0x00, 0x00, 0x9B,
        0xC6, 0x3A, 0x85, 0x2D, 0x3A, 0x3D, 0x4B, 0x7A, 0x23, 0x0F, 0x43, 0xD1, 0x6B, 0xA7, 0x03, 0x65, 0x3B, 0x1E,
        0x67, 0x3E, 0x51, 0x9D, 0x0C, 0xF8, 0xD4, 0x00, 0x00, 0x02, 0x13, 0x01, 0x01, 0x00,
    ];

    assert!(matches!(classify_l7(&client_hello, 44444, 443, true), L7Protocol::Dtls(_)));
}

#[test]
fn detects_dtls_handshake_records() {
    assert!(matches!(classify_l7(&[0x16, 0xFE, 0xFF, 0, 0, 0], 0, 443, true), L7Protocol::Dtls(_)));
    assert!(matches!(classify_l7(&[0x16, 0xFE, 0xFD, 0, 0, 0], 0, 443, true), L7Protocol::Dtls(_)));
}

#[test]
fn rejects_too_short_dtls_record_prefix() {
    assert!(matches!(classify_l7(&[0x16, 0xFE], 0, 4444, true), L7Protocol::Unknown));
}
