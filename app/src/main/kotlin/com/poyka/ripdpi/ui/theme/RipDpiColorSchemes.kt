fun ripDpiLightColorScheme(contrast: RipDpiContrastLevel = RipDpiContrastLevel.Standard): ColorScheme =
    when (contrast) {
        RipDpiContrastLevel.Standard -> LightStandardScheme
        RipDpiContrastLevel.Medium -> LightMediumScheme
        RipDpiContrastLevel.High -> LightHighScheme
    }

fun ripDpiDarkColorScheme(contrast: RipDpiContrastLevel = RipDpiContrastLevel.Standard): ColorScheme =
    when (contrast) {
        RipDpiContrastLevel.Standard -> DarkStandardScheme
        RipDpiContrastLevel.Medium -> DarkMediumScheme
        RipDpiContrastLevel.High -> DarkHighScheme
    }

