package com.poyka.ripdpi.core.detection

import org.junit.Assert.assertTrue
import org.junit.Test

class DetectionReportFormatterTest {
    @Test
    fun `copied report preserves endpoint failures DNS evidence and consensus`() {
        val comparison =
            com.poyka.ripdpi.core.detection.checker.IpComparisonChecker.evaluate(
                listOf(
                    IpComparisonEndpointResult(
                        IpComparisonEndpointDescriptor(
                            "RU reflector",
                            "https://example.invalid/ip",
                            IpComparisonEndpointGroup.RU,
                        ),
                        IpComparisonDnsRecords(aRecords = listOf("203.0.113.10")),
                        reflectedIp = null,
                        status = IpComparisonEndpointStatus.ERROR,
                        errorMessage = "HTTP 500",
                    ),
                ),
            )
        val consensus =
            com.poyka.ripdpi.core.detection.consensus.IpConsensusBuilder.build(
                emptyCategory("GeoIP"),
                emptyBypass(),
                comparison,
                null,
            )
        val result =
            DetectionCheckResult(
                geoIp = emptyCategory("GeoIP"),
                directSigns = emptyCategory("Direct"),
                indirectSigns = emptyCategory("Indirect"),
                locationSignals = emptyCategory("Location"),
                bypassResult = emptyBypass(),
                ipComparison = comparison,
                ipConsensus = consensus,
                verdict = Verdict.NOT_DETECTED,
            )

        val report = DetectionReportFormatter.format(result)

        assertTrue(report.contains("--- IP comparison ---"))
        assertTrue(report.contains("[ERROR] RU reflector"))
        assertTrue(report.contains("A=203.0.113.10"))
        assertTrue(report.contains("reason=HTTP 500"))
        assertTrue(report.contains("--- IP consensus ---\nStatus: INCONCLUSIVE"))
        assertTrue(DetectionReportFormatter.format(result, privacyModeEnabled = true).contains("A=203.0.*.*"))
    }

    @Test
    fun `unmeasured and failed checks are not reported as successful`() {
        val result =
            DetectionCheckResult(
                geoIp = emptyCategory("GeoIP").copy(executionStatus = CheckExecutionStatus.ERROR),
                directSigns = emptyCategory("Direct"),
                indirectSigns = emptyCategory("Indirect"),
                locationSignals = emptyCategory("Location"),
                bypassResult = emptyBypass(),
                dnsLeak =
                    com.poyka.ripdpi.core.detection.checker.DnsLeakChecker
                        .resultFrom(listOf("192.0.2.53"), true),
                verdict = Verdict.NOT_DETECTED,
            )

        val report = DetectionReportFormatter.format(result)

        assertTrue(report.contains("--- GeoIP ---\nStatus: ERROR"))
        assertTrue(report.contains("--- DNS settings ---\nStatus: OBSERVATION ONLY"))
    }

    private fun emptyCategory(name: String) =
        CategoryResult(
            name = name,
            detected = false,
            findings = emptyList(),
        )

    private fun emptyBypass() =
        BypassResult(
            proxyEndpoint = null,
            directIp = null,
            proxyIp = null,
            xrayApiScanResult = null,
            findings = emptyList(),
            detected = false,
        )

    @Test
    fun `report contains verdict`() {
        val result =
            DetectionCheckResult(
                geoIp = emptyCategory("GeoIP"),
                directSigns = emptyCategory("Direct"),
                indirectSigns = emptyCategory("Indirect"),
                locationSignals = emptyCategory("Location"),
                bypassResult = emptyBypass(),
                verdict = Verdict.NOT_DETECTED,
            )
        val report = DetectionReportFormatter.format(result)
        assertTrue(report.contains("Verdict: NOT_DETECTED"))
        assertTrue(report.contains("=== Detection Check Report ==="))
        assertTrue(report.contains("Generated by RIPDPI"))
    }

    @Test
    fun `report contains all sections`() {
        val result =
            DetectionCheckResult(
                geoIp = emptyCategory("GeoIP"),
                directSigns = emptyCategory("Direct"),
                indirectSigns = emptyCategory("Indirect"),
                locationSignals = emptyCategory("Location"),
                bypassResult = emptyBypass(),
                verdict = Verdict.DETECTED,
            )
        val report = DetectionReportFormatter.format(result)
        assertTrue(report.contains("--- GeoIP ---"))
        assertTrue(report.contains("--- Direct Signs ---"))
        assertTrue(report.contains("--- Indirect Signs ---"))
        assertTrue(report.contains("--- Location Signals ---"))
        assertTrue(report.contains("--- Bypass ---"))
    }

    @Test
    fun `report includes findings`() {
        val result =
            DetectionCheckResult(
                geoIp =
                    emptyCategory("GeoIP").copy(
                        findings =
                            listOf(
                                Finding("IP: 1.2.3.4"),
                                Finding("IP belongs to hosting provider: yes", detected = true),
                            ),
                    ),
                directSigns = emptyCategory("Direct"),
                indirectSigns = emptyCategory("Indirect"),
                locationSignals = emptyCategory("Location"),
                bypassResult = emptyBypass(),
                verdict = Verdict.NEEDS_REVIEW,
            )
        val report = DetectionReportFormatter.format(result)
        assertTrue(report.contains("IP: 1.2.3.4"))
        assertTrue(report.contains("! IP belongs to hosting provider: yes"))
    }

    @Test
    fun `report includes verdict narrative`() {
        val result =
            DetectionCheckResult(
                geoIp = emptyCategory("GeoIP").copy(detected = true),
                directSigns = emptyCategory("Direct"),
                indirectSigns = emptyCategory("Indirect"),
                locationSignals = emptyCategory("Location"),
                bypassResult = emptyBypass(),
                verdict = Verdict.DETECTED,
            )
        val report = DetectionReportFormatter.format(result)
        assertTrue(report.contains("--- Verdict Narrative ---"))
        assertTrue(report.contains("Exposure: Public IP only"))
        assertTrue(report.contains("Reasons:"))
    }
}
