package com.poyka.ripdpi.core.detection

import com.poyka.ripdpi.core.detection.privacy.DetectionPrivacyMask
import com.poyka.ripdpi.core.detection.privacy.redactAppIdentities

object DetectionReportFormatter {
    fun format(
        result: DetectionCheckResult,
        privacyModeEnabled: Boolean = false,
    ): String {
        val report = result.redactAppIdentities(privacyModeEnabled)
        return DetectionPrivacyMask.maskIpsInText(
            buildString {
                appendLine("=== Detection Check Report ===")
                appendLine()
                appendLine("Verdict: ${report.verdict}")
                appendLine()
                appendNarrative(report.verdictNarrative ?: VerdictNarrativeBuilder.build(report), privacyModeEnabled)

                appendCategory("GeoIP", report.geoIp)
                appendCategory("Direct Signs", report.directSigns)
                appendCategory("Indirect Signs", report.indirectSigns)
                appendCategory("Location Signals", report.locationSignals)
                appendBypass(report.bypassResult, privacyModeEnabled)
                report.dnsLeak?.let { appendCategory("DNS settings", it) }
                report.webRtcLeak?.let { appendCategory("WebRTC Leak", it) }
                appendCategory(LocalTlsReportTitle, report.tlsFingerprintForReport())
                report.timingAnalysis?.let { appendCategory("Timing Analysis", it) }
                report.icmpSpoofing?.let { appendCategory("ICMP Spoofing", it.category) }
                report.ipComparison?.let { appendCategory("IP comparison", it.category) }
                report.ipConsensus?.let { appendCategory("IP consensus", it.toCategoryResult()) }
                report.rttTriangulation?.let { appendCategory("RTT Triangulation", it.category) }
                report.callTransport?.let { appendCategory("Call Transport", it.category) }

                appendLine("Methodology: ${report.methodologyVersion}")

                val recommendations = DetectionRecommendations.generate(report)
                if (recommendations.isNotEmpty()) {
                    appendLine()
                    appendLine("--- Recommendations ---")
                    for (rec in recommendations) {
                        appendLine("* ${rec.title}: ${rec.description}")
                    }
                }

                appendLine()
                appendLine("Generated by RIPDPI Detection Check")
            },
            enabled = privacyModeEnabled,
        )
    }

    private fun StringBuilder.appendCategory(
        title: String,
        category: CategoryResult,
    ) {
        appendLine("--- $title ---")
        val status =
            when {
                category.detected -> {
                    "DETECTED"
                }

                category.needsReview -> {
                    "NEEDS REVIEW"
                }

                category.executionStatus != CheckExecutionStatus.COMPLETED -> {
                    category.executionStatus.name.replace(
                        '_',
                        ' ',
                    )
                }

                else -> {
                    "OK"
                }
            }
        appendLine("Status: $status")
        if ((category.detected || category.needsReview) && category.executionStatus != CheckExecutionStatus.COMPLETED) {
            appendLine("Execution: ${category.executionStatus.name}")
        }
        for (finding in category.findings) {
            val prefix =
                when {
                    finding.detected -> "!"
                    finding.needsReview -> "?"
                    else -> "-"
                }
            appendLine("  $prefix ${finding.description}")
        }
        appendLine()
    }

    private fun StringBuilder.appendNarrative(
        narrative: VerdictNarrative,
        privacyMode: Boolean,
    ) {
        appendLine("--- Verdict Narrative ---")
        appendLine("Exposure: ${narrative.exposureStatus.reportLabel()}")
        appendLine("Discovered:")
        for (row in narrative.discoveredRows) {
            appendLine("  - ${row.label}: ${DetectionPrivacyMask.narrativeValue(row, privacyMode)}")
        }
        appendLine("Reasons:")
        for (row in narrative.reasonRows) {
            appendLine("  - ${row.label}: ${row.value}")
        }
        narrative.homeRoutedRoamingNote?.let { note ->
            appendLine("Roaming note: $note")
        }
        appendLine()
    }

    private fun StringBuilder.appendBypass(
        bypass: BypassResult,
        privacyMode: Boolean,
    ) {
        appendLine("--- Bypass ---")
        val status =
            when {
                bypass.executionStatus != CheckExecutionStatus.COMPLETED -> bypass.executionStatus.name
                bypass.detected -> "DETECTED"
                bypass.needsReview -> "NEEDS REVIEW"
                else -> "OK"
            }
        appendLine("Status: $status")
        for (finding in DetectionPrivacyMask.bypassFindings(bypass, privacyMode)) {
            val prefix =
                when {
                    finding.detected -> "!"
                    finding.needsReview -> "?"
                    else -> "-"
                }
            appendLine("  $prefix ${finding.description}")
        }
        appendLine()
    }

    private fun ExposureStatus.reportLabel(): String =
        when (this) {
            ExposureStatus.REMOTE_ENDPOINT_DISCOVERED -> "Remote endpoint discovered"
            ExposureStatus.PUBLIC_IP_ONLY -> "Public IP only"
            ExposureStatus.LOCAL_PROXY_OR_API_ONLY -> "Local proxy or API only"
            ExposureStatus.TECHNICAL_SIGNAL_ONLY -> "Technical signal only"
            ExposureStatus.INSUFFICIENT_DATA -> "Insufficient data"
        }
}

internal fun DetectionCheckResult.tlsFingerprintForReport(): CategoryResult = tlsFingerprint ?: SkippedTlsFingerprint

internal const val LocalTlsReportTitle = "Local TLS settings"

private val SkippedTlsFingerprint =
    CategoryResult(
        name = LocalTlsReportTitle,
        detected = false,
        findings = emptyList(),
        executionStatus = CheckExecutionStatus.SKIPPED,
    )
